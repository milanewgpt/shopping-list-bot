def categorize(normalized_name: str) -> str:
    """Determine category for a normalized product name."""
    low = normalized_name.lower()

    # Exact multi-word patterns first (longer keys match first)
    for key in sorted(_KEYWORD_MAP, key=len, reverse=True):
        if key in low:
            return _KEYWORD_MAP[key]

    return "Прочее"
